"""Build a conservative convex peak envelope for every adjacent loop mixture.

A mix is multi-affine in RPM fraction and each node's load fraction. Interpolating
peak maxima at the eight cell corners upper-bounds every sample inside the cell.
Unrelated residual nodes are bounded by their individual absolute peaks.
This bound also covers arbitrary common integer-cycle offsets and convex joins.
"""
import argparse
import array
import hashlib
import json
from pathlib import Path
import sys

RPM_STEPS=16
LOAD_STEPS=4


def prepare(pcm_path,output):
    raw=pcm_path.read_bytes();pcm=array.array('h',raw)
    if sys.byteorder!='little':pcm.byteswap()
    assert len(pcm)==12*32768
    loops=[[v/32768 for v in pcm[n*32768:(n+1)*32768]] for n in range(12)]
    peaks=[max(map(abs,loop)) for loop in loops]
    table=[]
    for pair in range(5):
        start=pair*2
        low=[[(1-l/LOAD_STEPS)*a+(l/LOAD_STEPS)*b for a,b in zip(loops[start],loops[start+1])] for l in range(LOAD_STEPS+1)]
        high=[[(1-l/LOAD_STEPS)*a+(l/LOAD_STEPS)*b for a,b in zip(loops[start+2],loops[start+3])] for l in range(LOAD_STEPS+1)]
        for r in range(RPM_STEPS+1):
            t=r/RPM_STEPS
            for a in low:
                for b in high:
                    table.append(max(abs((1-t)*x+t*y) for x,y in zip(a,b))+1e-9)
    digest=hashlib.sha256(raw).hexdigest()
    source='// Generated by PrepareBounds.py from PCM SHA256 '+digest+'.\n'
    source+='public class PeakBounds {\n    let peaks:float64[] = ['+', '.join(format(v+1e-9,'.14g') for v in peaks)+']\n'
    source+='    let values:float64[] = [\n'
    for i in range(0,len(table),25):
        source+='        '+', '.join(format(v,'.14g') for v in table[i:i+25])+',\n'
    source+='    ]\n}\n'
    output.mkdir(parents=True,exist_ok=True)
    (output/'PeakBounds.sx').write_text(source)
    metadata=dict(pcm_sha256=digest,source_sha256=hashlib.sha256(source.encode()).hexdigest(),rpm_steps=RPM_STEPS,load_steps=LOAD_STEPS,values=len(table),ceiling=.98)
    (output/'PeakBounds.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print(json.dumps(metadata,indent=2))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('pcm',type=Path);p.add_argument('output',type=Path)
    a=p.parse_args();prepare(a.pcm,a.output)
