"""Reproduce listening test G: align recorded firing shapes, retaining noise.

Only the loaded 6000-RPM recording is used, as in the accepted isolated test.
Each real cycle is aligned by at most a quarter revolution using orders 1..12.
Overlapping two-cycle Hann windows apply those shifts to the stereo recording;
neither a synthetic pressure pulse nor a spectral reconstruction is substituted.
"""
import argparse
import array
import hashlib
import json
import math
from pathlib import Path
import sys
sys.dont_write_bytecode = True
from PrepareCompact import fft

FRAMES = 16384
CYCLE = 512


def pressure(values):
    spectrum = fft(values)
    for k in range(CYCLE):
        if min(k, CYCLE-k) == 0 or min(k, CYCLE-k) > 12:
            spectrum[k] = 0
    return [v.real for v in fft(spectrum, inverse=True)]


def prepare(path, output):
    raw = path.read_bytes()
    pcm = array.array('h', raw)
    if sys.byteorder != 'little': pcm.byteswap()
    assert len(pcm) == 12*FRAMES*2
    recording = [v/32768 for v in pcm[5*FRAMES*2:6*FRAMES*2]]
    reference = [(recording[i*2]+recording[i*2+1])/2 for i in range(FRAMES)]
    blocks = [pressure(reference[i*CYCLE:(i+1)*CYCLE]) for i in range(32)]
    template = [sum(block[i] for block in blocks)/32 for i in range(CYCLE)]
    shifts = [max(range(-128,129), key=lambda s: sum(block[(i+s)%CYCLE]*template[i] for i in range(CYCLE))) for block in blocks]
    aligned = [0.0]*(FRAMES*2)
    for cycle, shift in enumerate(shifts):
        centre = cycle*CYCLE
        for offset in range(-CYCLE,CYCLE):
            weight = .5+.5*math.cos(math.pi*offset/CYCLE)
            destination = (centre+offset)%FRAMES
            source = (centre+offset+shift)%FRAMES
            for channel in range(2):
                aligned[destination*2+channel] += weight*recording[source*2+channel]
    unfiltered = aligned[:]
    # Keep G unchanged at 7000. A second view of the SAME take removes only
    # frequencies that would alias when pitched up to 10500 RPM.
    for channel in range(2):
        spectrum = fft(aligned[channel::2])
        limit = 21000/(10500/60)*32
        for k in range(FRAMES):
            frequency = min(k,FRAMES-k)
            taper = max(0,min(1,(limit-frequency)/(limit*.04)))
            spectrum[k] *= taper
        aligned[channel::2] = [v.real for v in fft(spectrum,inverse=True)]
    gain = .97/max(max(map(abs,aligned)),max(map(abs,unfiltered)))
    loop = [round(v*gain*32768)/32768 for v in unfiltered+aligned]
    packed = array.array('h', [round(v*32768) for v in loop])
    if sys.byteorder != 'little': packed.byteswap()
    encoded = packed.tobytes()
    peak = max(map(abs,loop))+1e-9
    power = sum(v*v for v in loop[:FRAMES*2])/(FRAMES*2)
    correlation = sum(a*b for a,b in zip(unfiltered,aligned))/math.sqrt(sum(a*a for a in unfiltered)*sum(b*b for b in aligned))
    source = '// Generated by PrepareRegistered.py; real recorded cycles, aligned as listening test G.\n'
    source += 'public class RegisteredData {\n    let peak:float64 = '+format(peak,'.14g')+'\n'
    source += '    let power:float64 = '+format(power,'.14g')+'\n}\n'
    output.mkdir(parents=True,exist_ok=True)
    (output/'Assets').mkdir(exist_ok=True)
    (output/'Assets/Registered.pcm').write_bytes(encoded)
    (output/'RegisteredData.sx').write_text(source)
    metadata = dict(original_sha256=hashlib.sha256(raw).hexdigest(),pcm_sha256=hashlib.sha256(encoded).hexdigest(),
                    source_sha256=hashlib.sha256(source.encode()).hexdigest(),template_node=5,
                    alignment_orders=12,max_shift_samples=128,window_cycles=2,shifts=shifts,
                    anti_alias_maximum_rpm=10500,correlation_to_unfiltered_g=correlation,
                    anti_alias_transition_rpm=[7200,7500],audio_bytes=len(encoded))
    (output/'Assets/Registered.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print('Registered bank:', len(encoded), 'bytes; SHA256', metadata['pcm_sha256'])
    print('Node 5 shifts:', shifts)
    print('Correlation to isolated G:',correlation)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('pcm',type=Path); parser.add_argument('output',type=Path)
    args = parser.parse_args(); prepare(args.pcm,args.output)
